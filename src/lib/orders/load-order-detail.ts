import { prisma } from "@/lib/prisma";

/** Everything the dashboard order page shows, scoped to the owner. */
export function loadOwnerOrderDetail(ownerId: string, orderId: string) {
  return prisma.order.findFirst({
    where: { id: orderId, ownerId },
    select: {
      id: true,
      standId: true,
      orderNumber: true,
      createdAt: true,
      updatedAt: true,
      paymentMethod: true,
      paymentStatus: true,
      paymentTiming: true,
      localTransferMethodId: true,
      onlinePaymentProvider: true,
      saleOrigin: true,
      subtotalCents: true,
      totalCents: true,
      discountCents: true,
      discountLabel: true,
      promotionCodeSnapshot: true,
      shippingCents: true,
      gstCents: true,
      currency: true,
      depositCents: true,
      balanceCents: true,
      balanceDueAt: true,
      refundedCents: true,
      stripePaymentIntentId: true,
      squarePaymentId: true,
      paypalCaptureId: true,
      customerId: true,
      customerName: true,
      customerPhone: true,
      receiptEmail: true,
      isPreOrder: true,
      shopperSubscriptionId: true,
      collectionAt: true,
      collectionNote: true,
      collectionStatus: true,
      handoverMode: true,
      deliveryAddressLine1: true,
      deliverySuburb: true,
      deliveryPostcode: true,
      deliveryNotes: true,
      shippingCarrier: true,
      trackingNumber: true,
      trackingUrl: true,
      shippedAt: true,
      deliveredAt: true,
      stand: { select: { name: true, timezone: true } },
      fulfilment: {
        select: {
          fulfilmentStatus: true,
          optionLabel: true,
          pickupLocationName: true,
          pickupAddressSnapshot: true,
          windowLabel: true,
          deliveryZoneName: true,
        },
      },
      items: {
        orderBy: { createdAt: "asc" },
        select: {
          id: true,
          productId: true,
          productNameSnapshot: true,
          optionsSnapshot: true,
          quantity: true,
          unitPriceCents: true,
          lineTotalCents: true,
          product: { select: { imageUrl: true, sku: true } },
        },
      },
    },
  });
}

export type OrderDetail = NonNullable<Awaited<ReturnType<typeof loadOwnerOrderDetail>>>;
